function stringifyAgentSessionV3PilotRealCorpusBatchIntakeTemplateResult(
  result: AgentSessionV3PilotRealCorpusBatchIntakeTemplateResult,
  options: { prettyJson?: boolean } = {},
) {
  return JSON.stringify(result, null, options.prettyJson ? 2 : 0);
}

export async function runAgentSessionV3PilotRealCorpusBatchIntakeTemplate(
  options: RunAgentSessionV3PilotRealCorpusBatchIntakeTemplateOptions = {},
): Promise<AgentSessionV3PilotRealCorpusBatchIntakeTemplateResult> {
  const manifest = await createAgentSessionV3PilotRealCorpusBatchManifestTemplate();
  const index = createAgentSessionV3PilotRealCorpusBatchIndexTemplate();
  const noteText = createAgentSessionV3PilotRealCorpusBatchSampleNoteText();
  const readmeText = createAgentSessionV3PilotRealCorpusBatchReadmeText();
  const manifestPath = options.outDir
    ? path.join(options.outDir, 'real-corpus-manifest.json')
    : null;
  const indexPath = options.outDir
    ? path.join(options.outDir, 'corpus-batch-index.json')
    : null;
  const notePath = options.outDir
    ? path.join(options.outDir, 'sample-note-template.md')
    : null;
  const readmePath = options.outDir
    ? path.join(options.outDir, 'README.md')
    : null;

  const resultWithoutJson: AgentSessionV3PilotRealCorpusBatchIntakeTemplateResult = {
    index,
    indexPath,
    jsonText: null,
    kind: 'agent-session-v3-pilot-real-corpus-batch-intake-template',
    manifest,
    manifestPath,
    notePath,
    noteText,
    readmePath,
    readmeText,
    summaryText: [
      'AgentSessionV3PilotRealCorpusBatchIntakeTemplate',
      `sources=${manifest.sources?.length ?? 0}`,
      `batches=${index.batches?.length ?? 0}`,
      `outDir=${options.outDir ?? 'none'}`,
    ].join(' '),
    version: 1,
  };

  if (options.outDir && manifestPath && indexPath && notePath && readmePath) {
    await mkdir(options.outDir, {
      recursive: true,
    });
    await writeFile(
      manifestPath,
      JSON.stringify(manifest, null, options.prettyJson ? 2 : 0),
      'utf8',
    );
    await writeFile(
      indexPath,
      JSON.stringify(index, null, options.prettyJson ? 2 : 0),
      'utf8',
    );
    await writeFile(notePath, noteText, 'utf8');
    await writeFile(readmePath, readmeText, 'utf8');
  }

  return {
    ...resultWithoutJson,
    jsonText: options.includeJsonText
      ? stringifyAgentSessionV3PilotRealCorpusBatchIntakeTemplateResult(resultWithoutJson, {
        prettyJson: options.prettyJson,
      })
      : null,
  };
}

