function parseAgentSessionV3PilotRealCorpusBatchIntakeTemplateArgs(
  args: readonly string[],
): RunAgentSessionV3PilotRealCorpusBatchIntakeTemplateOptions {
  let includeJsonText = false;
  let outDir: string | null = null;
  let prettyJson = false;

  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    if (arg === '--json') {
      includeJsonText = true;
    } else if (arg === '--pretty') {
      includeJsonText = true;
      prettyJson = true;
    } else if (arg === '--out-dir') {
      const nextArg = args[index + 1];
      if (!nextArg) {
        throw new Error('Missing output directory after --out-dir.');
      }
      outDir = nextArg;
      index += 1;
    } else {
      throw new Error(`Unexpected argument: ${arg}`);
    }
  }

  return {
    includeJsonText,
    outDir,
    prettyJson,
  };
}

