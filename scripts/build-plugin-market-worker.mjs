import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

// Bundles the plugin market Worker into one file to paste into the Cloudflare dashboard
// (services/plugin-market/README.md). No credentials are included.
const source = fileURLToPath(new URL('../services/plugin-market/worker.mjs', import.meta.url));
const output = fileURLToPath(new URL('../services/plugin-market/worker.bundle.mjs', import.meta.url));
await build({
  entryPoints: [source], outfile: output, bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: false,
  banner: { js: '// Generated by scripts/build-plugin-market-worker.mjs. Deploy this file to Cloudflare Workers.' },
});
console.log('Prepared services/plugin-market/worker.bundle.mjs (no credentials included).');
