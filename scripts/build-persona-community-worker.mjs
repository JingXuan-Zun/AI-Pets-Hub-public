import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

const source = fileURLToPath(new URL('../services/persona-community/worker.mjs', import.meta.url));
const output = fileURLToPath(new URL('../services/persona-community/worker.bundle.mjs', import.meta.url));
await build({
  entryPoints: [source], outfile: output, bundle: true, format: 'esm', platform: 'browser', target: 'es2022',
  banner: { js: '// Generated by scripts/build-persona-community-worker.mjs. Deploy this file to Cloudflare Workers.' },
});
console.log('Prepared services/persona-community/worker.bundle.mjs (no credentials included).');
