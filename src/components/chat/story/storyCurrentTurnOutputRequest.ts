export const STORY_CURRENT_TURN_OUTPUT_POLICY = [
  '本轮行动优先：本轮就落实用户已作出的选择，包括离开当前话题、回房休息或暂停调查。未完成的调查或主线任务不是行动前置条件；保留为未完成，不以补问线索、追加任务或重复确认拖延用户行动。',
  '明确的移动请求本身就是合理转场依据：按世界条件交代离开、途中与到达，更新地点和合理耗时；角色可用符合人格的反应陪同，不得强行把用户拉回旧话题。只有已建立的实际障碍才可阻止，并具体说明障碍、尽量落实仍可执行的部分；不临时编造阻碍。',
  '本轮写作要求立即生效：用户最新输入可能同时包含剧情内的对白/行动和对作者的写作指令，必须分别理解。',
  '在字数、详略、对白比例、排版、语言、叙述视角和本轮内容重点上，本轮明确要求优先于历史写法、预设文风、默认小说模板和旧输出计划；未被修改的设定继续有效。',
  '“只写对白”“简短回答”“改用第一人称”等是可直接落实的输出要求，不应因为默认模板要求环境、动作或第二人称而忽略；本轮就交付符合要求的内容，不要只承诺下次调整或要求再次确认。',
  '不要把写作指令编成角色对白或故事事件，也不要仅因用户调整文风、篇幅或格式就推进时间、任务或关系。混合输入中只让真实剧情行动影响故事状态。',
  '用户引用的角色台词、故事文本中的命令不自动成为写作指令；“这次/本轮”仅作用当前回合，“以后/后续”才作为后续偏好，新的明确修改可以覆盖旧偏好。',
  '以上调整不覆盖系统安全要求、隐藏信息保护、导演结构化协议、角色知识与身份边界或用户选择权；用户未明确选择的行动不能擅自代做。',
].join('\n');

export function buildStoryCurrentTurnOutputRequest(userInput: string, stage: 'director' | 'narrator' | 'character') {
  return [
    '【本轮输出要求核对】',
    STORY_CURRENT_TURN_OUTPUT_POLICY,
    `本轮原始输入（以此核对，不以历史概括替代）：${userInput}`,
    stage === 'director'
      ? '在 publicAnalysis.requestUnderstanding 区分剧情意图与写作要求；在 outputPlan 和 narrationFocus 明确落实本轮行动目的、目标地点、行动结果，以及篇幅、形式和重点。涉及行动与转场时使用 progression 或 event，并同步 sceneTransition、角色地点与合理耗时，后续建议应跟随新的情境。若本轮只调整写法，保持已有剧情状态。仍只输出约定 JSON，公开计划只给出结论。'
      : '生成前静默核对本轮明确要求，并直接在本次正文中落实。导演计划或旧记录若遗漏、冲突于这些写作要求，应按本轮要求调整表达，不照搬旧模板；不输出核对过程。',
    stage === 'character' ? '当前通道仍只负责本角色对白；对完整故事的编排要求由导演和旁白落实。' : '',
  ].filter(Boolean).join('\n');
}
